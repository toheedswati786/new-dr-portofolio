                <p>Looking from the eyes of a behavioral health specialist, this day can bring a feeling of deep sadness for many survivors of domestic abuse or domestic violence. It can make them feel worthless all over again, depressed or vulnerable. They can easily decompensate with symptoms of PTSD and or depression.</p>
