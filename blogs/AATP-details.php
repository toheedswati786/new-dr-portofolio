                                            <h2>Gratitude: An Antidote to Perfectionism</h2>
                                            <p>My youngest son, born 6 weeks premature, developed some school related anxiety when he started the third grade. Around that age, children enter a phase of development where they becoming less egocentric and more aware of their surroundings and how they are perceived by others. All of a sudden, he started realizing he wasn’t as good at sports as he was at academics. Almost overnight, he went from being a shy, sweet and polite child into an angry one, who would lose control of his emotions if he would miss a goal or would drop a ball thrown to him. His behaviors started affecting his daily school activities, and even his class work.</p>
                                            <p>He started resisting going to school, which was once something that he loved and would do with enthusiasm. He’d come home disappointed in himself, no matter how much we tried to be there for him and let him vent his frustrations. We would reassure him and help him gently realize his strengths. Tell him how we all make mistakes and can’t be good at everything. I had exhausted every trick in the book I knew.</p>
                                            <p>That’s when both me and my husband realized that this apple had not fallen far from the tree. After all, what do you expect a kid of a high achieving cardiologist and a psychiatrist- who takes her career and her parenthood pretty seriously, to be? He couldn’t be someone who would be okay with getting a B on a test, or be totally cool with not scoring a goal, even though we’d wished we could raise him like that.</p>
                                            <p>Whatever it was- genes, psychology, premature birth, or just watching his overachieving parents give their 100 percent to everything- my son who used to love school was no longer interested in in it.</p>
                                            <p>Since our interventions didn’t work, we headed to a therapist. She completed a thorough evaluation, and it didn’t take her too long to realize that the source of our sons frustration was that he was in a gifted range. Gifted children and individuals often struggle with perfectionistic tendencies and are susceptible to higher levels of anxiety than their peers. She helped our son slowly to be ok with making mistakes and coached us to share our experiences with him. So we started celebrating our mistakes. A lot of times we had to fake it even, to model imperfection. She did meditation, deep breathing and relaxation exercises, and played board games with him until he slowly learned to not take things too seriously.</p>
                                            <p>It took a lot of patience on my part as well to try to stay silent during all those sessions with the therapist. She helped us to realize that we may have needed the help just as much as our son did!</p>
                                            <p>Something clicked in my head during one of those hour long therapy sessions with my son. It dawned on me that… this kid’s life was close to perfect. Perfect home, perfect room, almost perfect school, with amazing, compassionate teachers, a family who loved him unconditionally, delicious food to eat, places to visit, great books to read. There was hardly any thing imperfect in this kids life. And yes- we had done a perfect job in making his life that perfect!</p>
                                            <p>So it was no wonder that when things didn’t go his way, he didn’t like it. He didn’t like to feel lesser than others because he never had to experience that feeling before. Of course, all of the therapist’s interventions were helping, and definitely taught him great ways to calm his mind. But there was something else I felt might be quite helpful.</p>
                                            <p>We started a new exercise with him. We decided that every night, after we finish reading a bedtime story, we would start doing a gratitude prayer with him. We began this routine of lifting our hands and praying to Almighty, thanking him for the wonderful things that came our way during that day. We would start simply, with good health, our ability to feel, see, hear, walk and run. For a vehicle to take us to school, a beautiful yard to play with. We had friends to share with, teachers to learn from, a great school to feel safe and welcomed in. We had good food and a smart brain that helped us do well. We had a mind that could think so fast and could help us make choices, both good and bad.</p>
                                            <p>We also started thanking God for giving us the ability to make mistakes, and therefore an opportunity to learn from them. We would end our gratitude prayer by asking him to give whatever blessings He’s given us to all the other children of the world. We prayed for all kids in this world whose countries are going through wars and political unrest, who are suffering from malnourishment, hunger, and homelessness. We prayed and wished the same privileges for them that we’d been granted.</p>
                                            <p>To our surprise, with just a few minutes of gratitude each day, our son’s attitude started to change for the better. He loved this gratitude prayer routine, and insisted we do it with him every night. As the days went by, he became happier and happier. He started making wiser choices when it came to picking what games he liked, and even started trying new ones. He was handling his disappointments during game time with ease. He started learning how to self-soothe. He started playing solo games and seemed to enjoy that with out feeling left out. It was so heartwarming to see him slowly enjoy school once again, to engage in cooperative play with his peers, and to take interest in his class work the way he used to. And yes, there were still some days where he had his setbacks, but with a little time, he was able get back to his calm self. He even started opening up about such episodes, and he learnt how to forgive himself for getting upset.</p>
