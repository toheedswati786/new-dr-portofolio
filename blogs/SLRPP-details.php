                                            <p>It is that time of the year again! Being a psychiatrist, I often see how holidays can be a very challenging time not just for my patients, but for the general public as well. Their emotions can stir up pretty fast, thus leading to an enormous rise in their level of stress. </p>
                                            <p>This Holiday will be the second one during this time of a Pandemic. Thank God! It’s not as bad as it was last year when we could not even come out to greet each other. Our celebrations were limited to zoom calls and having to celebrate only with the closest family members. Grief and anxiety from COVID were at a level that we have never seen before in our lives.</p>
                                            <p><b>I come from the Muslim faith, and we celebrated our big holiday, Eid, in the month of May.</b> Eid, like any other holiday, can also become pretty stressful, even though it’s meant to be a relaxing and fun time for everyone. The Pandemic made me become more mindful of the real purpose, traditions, and values attached to this day, rather than having to focus on the material aspect of the celebration. So we came up with these simple strategies to incorporate into every Holiday from here on. We call them ” Eighth everlasting gifts of a Holiday celebration”. Here I wanted to share those with you so that your holiday season can be as memorable and less stressful, as ours.</p>
                                            <h2>1: The Gift of Awareness</h2>
                                            <p>Let’s try to be aware of the fact that we are in a very unusual time. We are all going through similar turbulent emotions. We are all struggling in some or another way. We are all very uncertain of the present situation and the future, which brings anxiety. We must try to remember and reassure ourselves that this too shall pass, like every other stressful time.</p>
                                            <h2>2. The Gift of Purpose</h2>
                                            <p>Let’s reflect on why we celebrate what we celebrate! The real purpose of our holidays, the actual spirit behind these celebrations. Why we decorate homes with lights, why we give gifts, why we gather and eat together, why we put up Menorahs or Christmas trees. By keeping the purpose of the holidays at the forefront of our mind, we can prevent ourselves from being sucked into consumerism and material attractions, which can put unnecessary stress on us, thus making a lot of us dread this time of the year. We can create new traditions, like gathering with our kids, and sharing stories about these celebrations, and their true essence.</p>
                                            <h2>3: The Gift of Being in the Present Moment</h2>
                                            <p>Let’s give our full attention to whatever activity we’re doing in a moment. Whether it be wrapping presents, making lists of gifts, invites, or the foods that we’ll be preparing for our loved ones. Let’s take breaks from whatever we’re doing to center ourselves, like taking a walk, doing a prayer, talking to a friend, or just doing nothing.</p>
                                            <h2>4: The Gift of Gratitude</h2>
                                            <p>Let’s be thankful for our daily blessings. Be grateful for the ability to buy presents, for being able to prepare delicious, simple, or elaborate meals. Let’s be grateful for the ability to stay warm this holiday season. And for those of us who are healthy and have survived COVID, there is even more of a reason to feel grateful- for!</p>
                                            <h2>5: The Gift of Empathy</h2>
                                            <p>Let’s try our best to feel the pain of those directly or indirectly affected by the challenges of the past two years of having to survive the pandemic. Thousands of people are still overcoming the grief of the loved ones they lost to COVID and some have not even begun the process yet. Let’s put ourselves in the shoes of our fellow humans who lost their jobs or homes, families separated at borders or elsewhere. Let us wish the same privileges that we have been blessed with, for the billions of those people who still live in poverty, survive in war-stricken areas or famine-affected nations, or who struggle to put food on their table.</p>
                                            <h2>6: The Gift of Simplicity</h2>
                                            <p>Let’s practice the long-lost value of simplicity by using less instead of more. Let’s try to keep our gifts simple yet sincere! Limit our dinner menus to just a few foods that everyone enjoys. Let’s consider wearing something that we already own instead of buying a new outfit. Let’s decorate our homes modestly, and enjoy the process.</p>
                                            <h2>7: The Gift of Imagination</h2>
                                            <p>Let’s revive the power of imagination that we used to have when we were little children. Imagine the North Pole, Santa Claus bringing us gifts, riding on his reindeers, and sliding down our chimneys. Let’s imagine the future, where we can go back to the movies, to restaurants, nice gatherings, block parties, graduations, and birthdays and not have to wear face masks or worry about contracting the virus.</p>
                                            <h2>8: The Gift of Self-Love</h2>
                                            <p>Let’s forgive ourselves more often and be as kind to ourselves as we are to others. Let’s be OK with not being OK for some time, and celebrate both our shortcomings and our strengths.</p>
                                            <p>Hopefully, with these simple yet effective strategies, we all can celebrate the true essence of holidays both during and after this pandemic. We can leave a legacy of these times being peaceful, grateful, and joyous, rather than being stressful and overwhelming.</p>
